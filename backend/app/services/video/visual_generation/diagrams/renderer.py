"""
High-resolution 16:9 SVG rendering engine for technical diagrams.

Milestone 5, Phase 5.2: Technical Diagram Generation.

Coordinates:
- Graphviz DOT compilation to vector SVG
- 16:9 (1920x1080) canvas compositing with educational video styling (header, badge, canvas, footer)
- Pure-Python vector fallback renderer if Graphviz is unavailable
- Validating output SVG syntax and dimensions
"""

from __future__ import annotations

import html
import logging
import re
import shutil
import subprocess
import time
from typing import List, Optional, Tuple

from .base import (
    CANVAS_HEIGHT,
    CANVAS_WIDTH,
    CATEGORY_COLORS,
    COLOR_ARROW,
    COLOR_CANVAS_BG,
    COLOR_CARD_BG,
    COLOR_TEXT_FAINT,
    COLOR_TEXT_MAIN,
    COLOR_TEXT_MUTED,
    DiagramType,
    sanitize_text,
)

logger = logging.getLogger(__name__)


class DiagramRenderer:
    """Renders Graphviz DOT into production-quality 1920x1080 SVGs for educational videos."""

    def __init__(self, dot_binary_path: Optional[str] = None):
        self.dot_path = dot_binary_path or shutil.which("dot") or "/opt/homebrew/bin/dot"

    def is_graphviz_available(self) -> bool:
        """Checks if graphviz 'dot' binary is executable on the system."""
        if not self.dot_path:
            return False
        try:
            res = subprocess.run([self.dot_path, "-V"], capture_output=True, timeout=2)
            return res.returncode == 0
        except Exception:
            return False

    def compile_dot_to_raw_svg(self, dot_source: str) -> Tuple[str, float, float]:
        """
        Runs `dot -Tsvg` on the DOT source and returns: (raw_svg, original_width_pt, original_height_pt).
        """
        if not self.is_graphviz_available():
            raise RuntimeError("Graphviz 'dot' executable not found on system PATH.")

        start_time = time.perf_counter()
        process = subprocess.run(
            [self.dot_path, "-Tsvg"],
            input=dot_source,
            capture_output=True,
            text=True,
            timeout=10,
            check=True,
        )
        raw_svg = process.stdout
        duration_ms = (time.perf_counter() - start_time) * 1000
        logger.debug("Compiled DOT to SVG in %.2f ms", duration_ms)

        # Parse viewBox="min-x min-y width height"
        viewbox_match = re.search(r'viewBox="([0-9\.\-]+)\s+([0-9\.\-]+)\s+([0-9\.\-]+)\s+([0-9\.\-]+)"', raw_svg)
        if viewbox_match:
            orig_w = float(viewbox_match.group(3))
            orig_h = float(viewbox_match.group(4))
        else:
            orig_w, orig_h = 1000.0, 600.0

        return raw_svg, orig_w, orig_h

    def composite_1080p_svg(
        self,
        raw_svg: str,
        orig_w: float,
        orig_h: float,
        title: str,
        subtitle: str,
        category_label: str,
        diagram_type: DiagramType,
        evidence_files: List[str],
    ) -> str:
        """
        Embeds the rendered diagram graph into a standardized 1920x1080 landscape canvas
        with an educational header, category pill badge, and evidence footer.
        """
        # Extract <g id="graph0">...</g>
        g_match = re.search(r"(<g id=\"graph0\"[\s\S]*?</g>)\s*</svg>", raw_svg)
        if not g_match:
            # If graph0 was not matched, extract entire inner content between <svg ...> and </svg>
            inner_match = re.search(r"<svg[^>]*>([\s\S]*?)</svg>", raw_svg)
            inner_content = inner_match.group(1) if inner_match else raw_svg
        else:
            inner_content = g_match.group(1)

        # Remove outer white background polygon if generated by Graphviz
        inner_content = re.sub(r'<polygon fill="white"[\s\S]*?/>', '', inner_content, count=1)
        inner_content = re.sub(r'<polygon fill="#ffffff"[\s\S]*?/>', '', inner_content, count=1)

        # Diagram viewport inside 1920x1080 canvas:
        # Available area: x in [80, 1840] (width 1760), y in [140, 980] (height 840)
        viewport_w = 1760.0
        viewport_h = 830.0
        viewport_x = 80.0
        viewport_y = 145.0

        scale = min(viewport_w / max(orig_w, 1.0), viewport_h / max(orig_h, 1.0), 1.6)
        scaled_w = orig_w * scale
        scaled_h = orig_h * scale

        # Center inside viewport
        offset_x = viewport_x + (viewport_w - scaled_w) / 2.0
        offset_y = viewport_y + (viewport_h - scaled_h) / 2.0

        # Colors for category badge
        badge_type = "core"
        if diagram_type == DiagramType.ARCHITECTURE:
            badge_type = "entrypoint"
        elif diagram_type == DiagramType.WORKFLOW:
            badge_type = "core"
        elif diagram_type == DiagramType.DATA_FLOW:
            badge_type = "storage"
        elif diagram_type == DiagramType.COMPONENT:
            badge_type = "external"

        badge_color = CATEGORY_COLORS.get(badge_type, CATEGORY_COLORS["core"])

        esc_title = html.escape(sanitize_text(title, max_length=70))
        esc_subtitle = html.escape(sanitize_text(subtitle, max_length=110))
        esc_badge = html.escape(category_label.upper())

        # Evidence files footer
        if evidence_files:
            clean_files = [sanitize_text(f, max_length=40) for f in evidence_files[:4]]
            ev_text = "Verified evidence: " + " • ".join(clean_files)
        else:
            ev_text = "Repository Knowledge Structure • Verified Architecture"
        esc_ev = html.escape(ev_text)

        # Composite complete 1080p SVG document
        svg_doc = f"""<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" viewBox="0 0 {CANVAS_WIDTH} {CANVAS_HEIGHT}" width="{CANVAS_WIDTH}" height="{CANVAS_HEIGHT}">
  <defs>
    <style>
      @import url('https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600;700&amp;display=swap');
      text {{ font-family: 'Inter', -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, Helvetica, Arial, sans-serif; }}
      .header-title {{ font-size: 28px; font-weight: 700; fill: {COLOR_TEXT_MAIN}; }}
      .header-sub {{ font-size: 15px; font-weight: 400; fill: {COLOR_TEXT_MUTED}; }}
      .badge-text {{ font-size: 12px; font-weight: 700; letter-spacing: 0.06em; fill: {badge_color['pill']}; }}
      .footer-text {{ font-size: 13px; font-weight: 500; fill: {COLOR_TEXT_FAINT}; }}
      .card-bg {{ fill: {COLOR_CARD_BG}; stroke: #E2E8F0; stroke-width: 1.5; rx: 16; }}
    </style>
    <filter id="card-shadow" x="-4%" y="-2%" width="108%" height="106%" filterUnits="userSpaceOnUse">
      <feDropShadow dx="0" dy="4" stdDeviation="8" flood-color="#0F172A" flood-opacity="0.04" />
    </filter>
  </defs>

  <!-- Background 16:9 Canvas -->
  <rect width="{CANVAS_WIDTH}" height="{CANVAS_HEIGHT}" fill="{COLOR_CANVAS_BG}" />

  <!-- Main Display Card Frame -->
  <rect x="40" y="30" width="1840" height="1020" class="card-bg" filter="url(#card-shadow)" />

  <!-- Header Section -->
  <g transform="translate(80, 56)">
    <!-- Category Pill Badge -->
    <rect x="0" y="0" width="{max(len(esc_badge) * 9 + 24, 140)}" height="26" rx="13" fill="{badge_color['bg']}" stroke="{badge_color['border']}" stroke-width="1" />
    <text x="12" y="17" class="badge-text">{esc_badge}</text>

    <!-- Scene Title & Subtitle -->
    <text x="0" y="52" class="header-title">{esc_title}</text>
    <text x="0" y="74" class="header-sub">{esc_subtitle}</text>
  </g>

  <!-- Divider Rule -->
  <line x1="80" y1="140" x2="1840" y2="140" stroke="#F1F5F9" stroke-width="2" />

  <!-- Embedded Technical Diagram Viewport -->
  <g transform="translate({offset_x:.2f}, {offset_y:.2f}) scale({scale:.4f})">
    {inner_content}
  </g>

  <!-- Footer Divider Rule -->
  <line x1="80" y1="1000" x2="1840" y2="1000" stroke="#F1F5F9" stroke-width="1.5" />

  <!-- Footer Section -->
  <g transform="translate(80, 1024)">
    <text x="0" y="0" class="footer-text">{esc_ev}</text>
    <text x="1760" y="0" text-anchor="end" class="footer-text">16:9 1080p • RepoGenie Visuals</text>
  </g>
</svg>"""
        return svg_doc

    def render_fallback_svg(
        self,
        nodes: List[dict],
        edges: List[dict],
        title: str,
        subtitle: str,
        category_label: str,
        diagram_type: DiagramType,
        evidence_files: List[str],
    ) -> str:
        """
        Pure-Python deterministic vector SVG generator used when Graphviz binary
        is missing or encounters an environment fault.
        """
        # Layout nodes horizontally or vertically
        total_nodes = max(len(nodes), 1)
        card_w = 260.0
        card_h = 110.0
        spacing_x = min(360.0, (1600.0 - card_w) / max(total_nodes - 1, 1))
        start_x = 100.0 + (1600.0 - ((total_nodes - 1) * spacing_x + card_w)) / 2.0
        start_y = 480.0

        node_positions = {}
        node_elements = []

        for i, n in enumerate(nodes):
            nx = start_x + i * spacing_x
            ny = start_y
            node_id = n.get("id", f"node_{i}")
            node_positions[node_id] = (nx + card_w / 2.0, ny + card_h / 2.0, nx, ny)

            n_title = html.escape(sanitize_text(n.get("label", node_id), max_length=24))
            n_sub = html.escape(sanitize_text(n.get("sublabel", ""), max_length=30))
            n_file = html.escape(sanitize_text(n.get("file", ""), max_length=32))

            cat = n.get("category", "core")
            colors = CATEGORY_COLORS.get(cat, CATEGORY_COLORS["core"])

            node_elements.append(f"""
    <g transform="translate({nx:.1f}, {ny:.1f})">
      <rect width="{card_w}" height="{card_h}" rx="12" fill="{colors['bg']}" stroke="{colors['border']}" stroke-width="2" />
      <text x="16" y="32" font-size="16" font-weight="700" fill="{colors['header']}">{n_title}</text>
      <text x="16" y="56" font-size="13" font-weight="400" fill="{COLOR_TEXT_MUTED}">{n_sub}</text>
      <rect x="16" y="72" width="{card_w - 32}" height="22" rx="4" fill="#FFFFFF" stroke="#E2E8F0" stroke-width="1" />
      <text x="24" y="87" font-size="11" font-weight="500" fill="{COLOR_TEXT_FAINT}">{n_file}</text>
    </g>""")

        edge_elements = []
        for e in edges:
            src = e.get("from")
            dst = e.get("to")
            if src in node_positions and dst in node_positions:
                sx, sy, snx, sny = node_positions[src]
                dx, dy, dnx, dny = node_positions[dst]
                x1 = snx + card_w
                y1 = sy
                x2 = dnx
                y2 = dy
                lbl = html.escape(sanitize_text(e.get("label", ""), max_length=20))
                mid_x = (x1 + x2) / 2.0
                edge_elements.append(f"""
    <g>
      <line x1="{x1:.1f}" y1="{y1:.1f}" x2="{x2:.1f}" y2="{y2:.1f}" stroke="{COLOR_ARROW}" stroke-width="2.5" marker-end="url(#arrow)" />
      {f'<text x="{mid_x:.1f}" y="{y1 - 10:.1f}" font-size="12" font-weight="600" text-anchor="middle" fill="{COLOR_TEXT_MUTED}">{lbl}</text>' if lbl else ''}
    </g>""")

        content_svg = f"""<g id="fallback_graph">
  <defs>
    <marker id="arrow" viewBox="0 0 10 10" refX="8" refY="5" markerWidth="6" markerHeight="6" orient="auto-start-reverse">
      <path d="M 0 1 L 10 5 L 0 9 z" fill="{COLOR_ARROW}" />
    </marker>
  </defs>
  {''.join(edge_elements)}
  {''.join(node_elements)}
</g>"""
        return self.composite_1080p_svg(
            raw_svg=f"<svg>{content_svg}</svg>",
            orig_w=1600.0,
            orig_h=600.0,
            title=title,
            subtitle=subtitle,
            category_label=category_label,
            diagram_type=diagram_type,
            evidence_files=evidence_files,
        )

    def render_diagram(
        self,
        dot_source: str,
        title: str,
        subtitle: str,
        category_label: str,
        diagram_type: DiagramType,
        evidence_files: List[str],
        fallback_nodes: Optional[List[dict]] = None,
        fallback_edges: Optional[List[dict]] = None,
    ) -> str:
        """
        Primary entry point: attempts Graphviz compilation first; seamlessly
        falls back to deterministic pure-vector SVG if Graphviz is missing.
        """
        try:
            if self.is_graphviz_available():
                raw_svg, orig_w, orig_h = self.compile_dot_to_raw_svg(dot_source)
                return self.composite_1080p_svg(
                    raw_svg=raw_svg,
                    orig_w=orig_w,
                    orig_h=orig_h,
                    title=title,
                    subtitle=subtitle,
                    category_label=category_label,
                    diagram_type=diagram_type,
                    evidence_files=evidence_files,
                )
        except Exception as exc:
            logger.warning("Graphviz compilation failed (%s); switching to vector SVG fallback.", exc)

        return self.render_fallback_svg(
            nodes=fallback_nodes or [],
            edges=fallback_edges or [],
            title=title,
            subtitle=subtitle,
            category_label=category_label,
            diagram_type=diagram_type,
            evidence_files=evidence_files,
        )


# Singleton renderer
diagram_renderer = DiagramRenderer()
